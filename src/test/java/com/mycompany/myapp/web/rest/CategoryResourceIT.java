    @Test
    @Transactional
    void putNewCategory() throws Exception {
        // Initialize the database
        categoryRepository.saveAndFlush(category);

        int databaseSizeBeforeUpdate = categoryRepository.findAll().size();

        // Update the category
        Category updatedCategory = categoryRepository.findById(category.getId()).get();
        // Disconnect from session so that the updates on updatedCategory are not directly saved in db
        em.detach(updatedCategory);
        updatedCategory
            .name(UPDATED_NAME)
            .countChanellInCategory(UPDATED_COUNT_CHANELL_IN_CATEGORY)
            .isDelete(UPDATED_IS_DELETE)
            .date1(UPDATED_DATE_1)
            .date2(UPDATED_DATE_2)
            .long1(UPDATED_LONG_1)
            .string1(UPDATED_STRING_1)
            .boolean1(UPDATED_BOOLEAN_1);

        restCategoryMockMvc
            .perform(
                put(ENTITY_API_URL_ID, updatedCategory.getId())
                    .contentType(MediaType.APPLICATION_JSON)
                    .content(TestUtil.convertObjectToJsonBytes(updatedCategory))
            )
            .andExpect(status().isOk());

        // Validate the Category in the database
        List<Category> categoryList = categoryRepository.findAll();
        assertThat(categoryList).hasSize(databaseSizeBeforeUpdate);
        Category testCategory = categoryList.get(categoryList.size() - 1);
        assertThat(testCategory.getName()).isEqualTo(UPDATED_NAME);
        assertThat(testCategory.getCountChanellInCategory()).isEqualTo(UPDATED_COUNT_CHANELL_IN_CATEGORY);
        assertThat(testCategory.getIsDelete()).isEqualTo(UPDATED_IS_DELETE);
        assertThat(testCategory.getDate1()).isEqualTo(UPDATED_DATE_1);
        assertThat(testCategory.getDate2()).isEqualTo(UPDATED_DATE_2);
        assertThat(testCategory.getLong1()).isEqualTo(UPDATED_LONG_1);
        assertThat(testCategory.getString1()).isEqualTo(UPDATED_STRING_1);
        assertThat(testCategory.getBoolean1()).isEqualTo(UPDATED_BOOLEAN_1);
    }

